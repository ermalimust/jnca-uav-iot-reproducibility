    for r in trigger_tests:
        trigger_lines.append(f"{r['label']} & {r['metric_label']} & ${r['delta']:+.4f}$ & {ci_tex(r)} & {tex_p(r['p_holm'])} & {tex_p(r['p_bh'])} \\\\")
    trigger_lines += [r'\bottomrule',r'\end{tabular}',r'\end{table}', '',r'\begin{revision}',
        r'The keyword parser also improves branch correctness on this familiar vocabulary. The finding supports the use of mission context in candidate construction, with benefits available to both keyword and language-model interfaces. It complements the held-out semantic comparison and the strong aggregate results of broad or exhaustive candidate exposure.',r'\end{revision}','']

