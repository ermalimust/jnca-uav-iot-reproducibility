        r'The held-out wording family in Table~\ref{tab:ood-cluster-tests} addresses semantic generalization; the triggered family in Table~\ref{tab:triggered-tests} addresses conditional branch selection; the present family addresses decision-layer trade-offs. Multiplicity control is scoped to each of these scientific questions. Other reported contrasts are descriptive unless accompanied by their stated paired inference. Resampling characterizes variation across the evaluated missions with the archived diagnostic pool held fixed.',
