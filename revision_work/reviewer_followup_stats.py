def sha(data): return hashlib.sha256(data).hexdigest()
def finite(s):
    try: v = float(s)
    except (TypeError, ValueError): return None
    return v if np.isfinite(v) else None
def dump(value): return (json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + '\n').encode()
def csv_bytes(rows):
    stream = io.StringIO(newline='')
    writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
    writer.writeheader(); writer.writerows(rows)
    return stream.getvalue().encode()
def tex_p(p): return '$<0.0001$' if p < .0001 else f'{p:.4f}'
def signed_sums(d):
    d=np.asarray(d,dtype=float)
    assignments=np.arange(2**len(d),dtype=np.uint64)[:,None]
    signs=(((assignments >> np.arange(len(d),dtype=np.uint64)) & 1).astype(float)*2-1)
    return (signs*d).sum(1)
def exact_sign_flip(d):
    # Every full sign assignment is one pair of half assignments. Sorting the
    # right half permits exact tail counting without building 2^30 rows.
    n=len(d); observed=abs(float(np.sum(d))); tolerance=n*1e-14
    if observed <= tolerance: return 1.0
    left=signed_sums(d[:n//2]); right=np.sort(signed_sums(d[n//2:]))
    upper=len(right)-np.searchsorted(right,observed-tolerance-left,side='left')
    lower=np.searchsorted(right,-observed+tolerance-left,side='right')
    count=int(upper.sum())+int(lower.sum())
    assert 0<=count<=2**n
    p=count/2**n
    if n<=12:
        # Direct exhaustive cross-check of the meet-in-the-middle implementation.
        direct=float(np.mean(abs(signed_sums(d))>=observed-tolerance))
        assert p==direct
    return p
def infer(d):
    d = np.asarray(d, dtype=float)
    n = len(d)
    assert np.isfinite(d).all() and n in (12, 30)
    # Restarting the fixed RNG gives common paired mission draws within a family.
    rng = np.random.default_rng(BOOT_SEED)
    draws = rng.integers(0, n, size=(BOOT, n))
    ci = np.quantile(d[draws].mean(1), [.025, .975])
    p=exact_sign_flip(d)
    test,reps='exact_sign_flip_meet_in_middle',2**n
    return dict(n=n, delta=float(d.mean()), ci_low=float(ci[0]), ci_high=float(ci[1]),
                p_raw=float(p), sign_flip_method=test, sign_flip_assignments=reps)
def adjust(rows):
    order = np.argsort([r['p_raw'] for r in rows]); m = len(rows)
    running = 0.
    for rank, j in enumerate(order):
        running = max(running, min(1., (m-rank)*rows[j]['p_raw']))
        rows[j]['p_holm'] = float(running)
    running = 1.
    for rank in range(m-1, -1, -1):
        j = order[rank]
        running = min(running, rows[j]['p_raw']*m/(rank+1))
        rows[j]['p_bh'] = float(running)
    for row in rows: row['holm_significant_005'] = row['p_holm'] < .05

def main(check=False):
    with zipfile.ZipFile(ZIP) as z: members = {name:z.read(name) for name in SOURCE_MEMBERS}
    data = {name:list(csv.DictReader(io.StringIO(members[name].decode('utf-8-sig'))))
            for name in [TRIGGER, MAIN1, MAIN2, CROSS]}
    # Triggered outcomes: average finite paired seed means within each mission,
    # then give each mission equal weight. Zero-triggered metrics stay undefined.
    trows = data[TRIGGER]; keyed = {}
    for r in trows:
        key = (r['mission'], int(r['seed']), r['method'])
        assert key not in keyed
        keyed[key] = r
    missions = sorted({r['mission'] for r in trows}); seeds = sorted({int(r['seed']) for r in trows})
    assert len(missions) == 12 and seeds == list(range(10))
    omitted = []; means = {}; mission_rows = []; plot_rows = []
    for mission in missions:
        for seed in seeds:
            ref = keyed[(mission, seed, 'mission_blind_template')]
            ntr = float(ref['n_triggered'])
            for _, method in TRIGGER_METHODS:
                r = keyed[(mission, seed, method)]
                assert float(r['n_triggered']) == ntr and r['n_windows'] == ref['n_windows']
                for metric, _ in TRIGGER_METRICS:
                    assert (finite(r[metric]) is None) == (ntr == 0)
            if ntr == 0: omitted.append(dict(mission=mission, seed=seed, n_triggered=0))
        for label, method in TRIGGER_METHODS:
            for metric, metric_label in TRIGGER_METRICS:
                valid = [(s, finite(keyed[(mission,s,method)][metric])) for s in seeds]
                valid = [(s,v) for s,v in valid if v is not None]
                assert len(valid) in (9,10)
                value = float(np.mean([v for _,v in valid])); means[(mission,method,metric)] = value
                mission_rows.append(dict(mission=mission, method=method, metric=metric,
                                         included_seeds=';'.join(str(s) for s,_ in valid), n_seeds=len(valid), mean=value))
    assert len(omitted) == 2
    for label, method in TRIGGER_METHODS:
        for metric, metric_label in TRIGGER_METRICS:
            values = np.array([means[(m,method,metric)] for m in missions])
            ci = infer(values)
            plot_rows.append(dict(label=label, method=method, metric=metric, mean=float(values.mean()),
                                  ci_low=ci['ci_low'], ci_high=ci['ci_high'], n_missions=12))
    trigger_tests = []
    for label, method in TRIGGER_METHODS[1:]:
        for metric, metric_label in TRIGGER_METRICS:
            d = [means[(m,method,metric)]-means[(m,'mission_blind_template',metric)] for m in missions]
            trigger_tests.append(dict(family='triggered_six_tests', label=label, method=method,
                reference='mission_blind_template', metric=metric, metric_label=metric_label, **infer(d)))
    adjust(trigger_tests)
    fraction_by_mission = []
    for mission in missions:
        vals = [keyed[(mission,s,'mission_blind_template')] for s in seeds]
        fraction_by_mission.append(np.mean([float(r['n_triggered'])/float(r['n_windows']) for r in vals]))
    triggered_fraction = float(np.mean(fraction_by_mission))

    # Recompute the original decision-layer/crossed family from raw rows.
    # In crossed data, average archetypes within seed, then seeds within mission.
    pairwise = []; pair_missions = []; inclusion = []
    for label, filename, scope, ma, mb, expected_n in COMPARISONS:
        sub = [r for r in data[filename] if (scope is None or r['scope']==scope) and r['method'] in (ma,mb)]
        cells = defaultdict(list); unique_keys=set()
        for r in sub:
            key = (r['mission'], int(r['seed']), r.get('archetype',''), r['method'])
            assert key not in unique_keys; unique_keys.add(key)
            cells[(r['mission'],int(r['seed']),r['method'])].append(r)
        mids = sorted({r['mission'] for r in sub}); assert len(mids)==expected_n
        # Pair the same seeds and, where applicable, the same archetypes.
        for m in mids:
            for s in range(10):
                a = cells[(m,s,ma)]; b = cells[(m,s,mb)]
                assert len(a)==len(b)==(5 if scope else 1)
                assert sorted(r.get('archetype','') for r in a)==sorted(r.get('archetype','') for r in b)
        for metric, metric_label in [('mean_regret','Regret'),('invalid_action_rate','Invalidity')]:
            method_means={}
            for m in mids:
                for method in (ma,mb):
                    seed_means=[]
                    for seed in range(10):
                        values=[finite(r[metric]) for r in cells[(m,seed,method)]]
                        assert all(v is not None for v in values)
                        seed_means.append(np.mean(values))
                    method_means[(m,method)]=float(np.mean(seed_means))
            d=[method_means[(m,ma)]-method_means[(m,mb)] for m in mids]
            result=dict(family='main_crossed_fourteen_tests',comparison=label,source=filename,
                        scope=scope or 'all',method_a=ma,method_b=mb,metric=metric,metric_label=metric_label,
                        mean_a=float(np.mean([method_means[(m,ma)] for m in mids])),
                        mean_b=float(np.mean([method_means[(m,mb)] for m in mids])),**infer(d))
            pairwise.append(result)
            pair_missions.extend(dict(comparison=label,metric=metric,mission=m,mean_a=method_means[(m,ma)],
                                      mean_b=method_means[(m,mb)],delta=v) for m,v in zip(mids,d))
        inclusion.append(dict(comparison=label,n_missions=len(mids),seeds_per_mission=10,
                              rows_per_seed_method=5 if scope else 1,
                              archetypes=sorted({r.get('archetype','') for r in sub}) if scope else []))
    assert len(pairwise)==14; adjust(pairwise)
    assert abs(pairwise[0]['mean_a']-.4863962962962962)<1e-12
    # Independent arithmetic cross-check for all equal-cell-size mission means.
    for r in pairwise:
        original=data[r['source']]
        for method, key in [(r['method_a'],'mean_a'),(r['method_b'],'mean_b')]:
            values=[float(x[r['metric']]) for x in original if x['method']==method and
                    (r['scope']=='all' or x['scope']==r['scope'])]
            assert abs(float(np.mean(values))-r[key])<1e-12

    # TeX replacements include complete subsection boundaries but no following subsection.
