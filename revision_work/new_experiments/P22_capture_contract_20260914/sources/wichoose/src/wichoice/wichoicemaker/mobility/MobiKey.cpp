#include <string>  // std::string
#include <sstream> // std::stringstream, std::istringstream

#include "../../../util/log/LogFile.hpp" // LOG_*
 
#include "MobiKey.hpp" // class MobiKey

/**
 * Constructor method that takes the relevant mobility features in directly.
 *
 * @param rpos: position relative to access point, in meters.
 * @param dir: vehicle orientation, in degrees from north.
 * @param hispeed: whether the vehicle is moving at  speed or not.
 */
MobiKey::MobiKey(const int rpos, 
                 const uint16_t dir,
                 const bool hispeed) : rpos(rpos),
                                       dir(dir),
                                       hispeed(hispeed) { }

/**
 * Constructor that parses required info from a string.
 *
 * @param str: a string generated by toString().
 * @throws std::invalid argument exception if argument does not represent valid mobility key.
 */
MobiKey::MobiKey(std::string const& str) {
  
  std::string taway; // throwaway string
  std::istringstream iss(str); // convert to stream
  
  // line format: mobikey rpos $1 dir $2 stop $3
  iss >> taway >>
         taway >> this->rpos >>
         taway >> this->dir >>
         taway >> this->hispeed;
  
  if (iss.fail())
    throw std::invalid_argument("String cannot be parsed into mobility key.");
}

/**
 * Tests the equality of two MobiKeys based on their individual components.
 *
 * @param okey: the key we're comparing against.
 * @return true if the key components are equal, and false otherwise.
 */
bool MobiKey::operator== (MobiKey const& okey) const {
  return this->rpos == okey.rpos && 
         this->dir == okey.dir &&
         this->hispeed == okey.hispeed;
}

/**
 * Tests the inequality of two MobiKeys based on their individual components.
 *
 * @param okey: the key we're comparing against.
 * @return true if the key components are different, and false otherwise.
 */
bool MobiKey::operator!= (MobiKey const& okey) const {
  return this->rpos != okey.rpos ||
         this->dir != okey.dir ||
         this->hispeed != okey.hispeed;
}

/**
 * Tests whether the object is smaller than another.
 *
 * @param okey: the key we're comparing against.
 * @return true if the key is smaller than okey, and  false otherwise.
 */
bool MobiKey::operator< (MobiKey const& okey) const {
  // order by: position, then by direction, then speed
  return this->rpos < okey.rpos ||
         (this->rpos == okey.rpos && this->dir < okey.dir) ||
         (this->rpos == okey.rpos && this->dir == okey.dir &&
                                     this->hispeed < okey.hispeed);
}

/**
 * Returns a textual representation of the mobility key.
 *
 * @return a textual representation of the mobility key.
 */
std::string MobiKey::toString() const {
  std::stringstream ss;
  ss << "mobikey rpos " << this->rpos <<
        " dir " << unsigned(this->dir) <<
        " hispeed " << this->hispeed;

  return ss.str();
}
